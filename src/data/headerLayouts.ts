/**
 * Byte-level header layouts used by the protocol tree.
 *
 * Rules:
 * - `bytes` is the fixed size of the header, or null when the layout is
 *   variable (text protocols, TLV formats, QUIC varints).
 * - Every field's `bits` must add up to `bytes * 8` for fixed layers; the test
 *   suite enforces this.
 * - `aliases` map a field to the keys used in the step payload so the UI can
 *   bind a value. Missing values render as "not in this step".
 */

export interface HeaderField {
  name: string;
  bits: number | null;
  description: string;
  aliases?: string[];
}

export interface HeaderLayer {
  id: string;
  name: string;
  bytes: number | null;
  fields: HeaderField[];
  note?: string;
}

